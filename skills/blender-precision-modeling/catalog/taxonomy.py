def build():
    """Return the full catalog as plain data, ready for JSON."""
    items = []
    for dom_id, dom_title, note, rows in DOMAINS:
        for item_id, name, size, recipes in rows:
            lo, hi = SIZE[size]
            items.append(OrderedDict([
                ("id", item_id),
                ("name", name),
                ("domain", dom_id),
                ("domain_title", dom_title),
                ("size_class", size),
                ("size_mm", [lo, hi]),
                ("recipes", recipes),
                ("status", "todo"),
            ]))
    domains = [OrderedDict([("id", d[0]), ("name", d[1]), ("notes", d[2]),
                            ("count", len(d[3]))]) for d in DOMAINS]
    return OrderedDict([
        ("version", "1.0"),
        ("size_classes", OrderedDict((k, list(v)) for k, v in SIZE.items())),
        ("domains", domains),
        ("items", items),
    ])


