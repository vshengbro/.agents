    import json
    import os
    cat = build()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "catalog.json")
    with open(out, "w") as fh:
        json.dump(cat, fh, indent=1)
    print("wrote %s: %d domains, %d items"
          % (out, len(cat["domains"]), len(cat["items"])))